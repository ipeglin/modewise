"""Regenerate src/filters.rs: scaling filters from PyWavelets (MIT; notice in THIRD_PARTY_NOTICES.md).

Usage: uv run --no-project --with PyWavelets python generate.py

Each entry is the scaling (low-pass) filter g of Percival and Walden (2000), which is pywt's
rec_lo. The wavelet filter h follows from g by the quadrature mirror relation
h_l = (−1)^l g_{L−1−l}; this script checks that pywt's rec_hi agrees.
"""

from pathlib import Path

import numpy as np
import pywt

names = ["haar"] + [f"db{i}" for i in range(1, 11)] + [f"sym{i}" for i in range(2, 11)] + [f"coif{i}" for i in range(1, 6)]
lines = [
    "//! Scaling filters g (pywt `rec_lo`), generated by `filters/generate.py` from PyWavelets",
    f"//! {pywt.__version__} (MIT; notice in THIRD_PARTY_NOTICES.md). Do not edit by hand.",
    "",
    "#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::unreadable_literal)]",
    "",
    "#[rustfmt::skip]",
    "pub(crate) const FILTERS: &[(&str, &[f64])] = &[",
]
for name in names:
    w = pywt.Wavelet(name)
    g = np.array(w.rec_lo)
    L = len(g)
    h = np.array([(-1) ** l * g[L - 1 - l] for l in range(L)])
    assert np.allclose(h, w.rec_hi, atol=1e-15), name
    # pywt's symlet tables are accurate to about 5e-12 (sym3); the others to 1e-12.
    assert abs(g.sum() - np.sqrt(2)) < 1e-11 and abs((g * g).sum() - 1) < 1e-11, name
    values = ", ".join(repr(float(v)) for v in g)
    lines.append(f'    ("{name}", &[{values}]),')
lines.append("];")
(Path(__file__).parent.parent / "src" / "filters.rs").write_text("\n".join(lines) + "\n")
print(len(names), "filters")
